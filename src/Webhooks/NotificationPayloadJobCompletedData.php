    use SdkModel;

    /**
     * List of files generated by the job.
     *
     * @var list<JobFile> $files
     */
    #[Required(list: JobFile::class)]
    public array $files;

    #[Required]
    public Job $job;

    /**
     * `new NotificationPayloadJobCompletedData()` is missing required properties by the API.
     *
     * To enforce required parameters use
     * ```
     * NotificationPayloadJobCompletedData::with(files: ..., job: ...)
     * ```
     *
     * Otherwise ensure the following setters are called
     *
     * ```
     * (new NotificationPayloadJobCompletedData)->withFiles(...)->withJob(...)
     * ```
     */
    public function __construct()
    {
        $this->initialize();
    }

    /**
     * Construct an instance from the required parameters.
     *
     * You must use named parameters to construct any parameters with a default value.
     *
     * @param list<JobFile|JobFileShape> $files
     * @param Job|JobShape $job
     */
    public static function with(array $files, Job|array $job): self
    {
        $self = new self;

        $self['files'] = $files;
        $self['job'] = $job;

        return $self;
    }

    /**
     * List of files generated by the job.
     *
     * @param list<JobFile|JobFileShape> $files
     */
    public function withFiles(array $files): self
    {
        $self = clone $this;
        $self['files'] = $files;

        return $self;
    }

    /**
     * @param Job|JobShape $job
     */
    public function withJob(Job|array $job): self
    {
        $self = clone $this;
        $self['job'] = $job;

        return $self;
    }
}
